import { readFile, writeFile } from 'node:fs/promises';
const logic = (await readFile(new URL('./logic.js', import.meta.url), 'utf8')).replace(/^export /gm, '');
const source = await readFile(new URL('./client.source.js', import.meta.url), 'utf8');
if (!source.includes('/* DSH_USAGE_LOGIC */')) throw new Error('Missing logic insertion marker');
await writeFile(new URL('./client.js', import.meta.url), '// Generated by node build.mjs; edit client.source.js / logic.js.\n' + source.replace('/* DSH_USAGE_LOGIC */', () => logic));
